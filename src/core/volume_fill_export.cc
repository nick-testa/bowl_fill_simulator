/// Shortest text that reads back as exactly `v`, so lab37 computes with the same
/// doubles the simulator did.
std::string num(double v)
{
    return std::format("{}", v);
}

/// A C++ string literal.
std::string quoted(const std::string &s)
{
    return "\"" + replace_all(replace_all(s, "\\", "\\\\"), "\"", "\\\"") + "\"";
}

std::string kind_enumerator(const std::string &kind)
{
    if (kind == "base")
    {
        return "Base";
    }
    if (kind == "protein")
    {
        return "Protein";
    }
    if (kind == "sauce")
    {
        return "Sauce";
    }
    return "Topping";
}

bool same_curve(const VolumeFillRow &a, const VolumeFillRow &b)
{
    return a.kind == b.kind && a.ml_at_1_g == b.ml_at_1_g && a.volume_exponent == b.volume_exponent &&
           a.piece_height_mm == b.piece_height_mm;
}

